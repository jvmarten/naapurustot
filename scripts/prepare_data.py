def clean_properties(gdf):
    """Replace Paavo -1 suppression sentinels with None across all source columns.

    IN-1: Statistics Finland (Paavo) uses -1 as a confidentiality/suppression marker
    on every he_/ko_/hr_/tr_/te_/ra_/pt_/tp_ column (plus pinta_ala). Sweep the whole
    prefix set rather than a hand-maintained allowlist, so no suppression sentinel can
    leak into region_properties.json, the open-data CSV or /api/v1 as if it were a
    count. The 3 derived *_change_pct metrics legitimately hold real -1.0 % values and
    are outside this prefix scope, so they are left untouched.
    """
    suppression_prefixes = ("he_", "ko_", "hr_", "tr_", "te_", "ra_", "pt_", "tp_")
    for col in gdf.columns:
        if col.startswith(suppression_prefixes) or col == "pinta_ala":
            gdf[col] = gdf[col].apply(lambda v: None if v == -1 or v == -1.0 else v)
    # QW-1: the Paavo household-income (tr_*) and living-space (te_as_valj) columns
    # use BOTH -1 and 0 as confidentiality/zero-suppression sentinels (0 is never a
    # real value for these), so null both — otherwise the 0s pull the color scale
    # and national p2 range to zero. Targeted so other fields where 0 is legitimate
    # (counts) are untouched.
    zero_suppressed_fields = ["tr_mtu", "tr_ktu", "te_as_valj"]
    for col in zero_suppressed_fields:
        if col in gdf.columns:
            gdf[col] = gdf[col].apply(lambda v: None if v in (-1, -1.0, 0, 0.0) else v)
    return gdf


def fetch_property_prices():
    """Fetch apartment price data (€/m²) per postal code from Statistics Finland."""
    logger.info("Fetching property price data from Statistics Finland...")

    try:
        meta_r = _request_with_retry(
            "GET", PROPERTY_PRICE_URL, label="property price metadata", timeout=30,
        )
        meta = meta_r.json()
        variables = _validate_pxweb_meta(meta, "property price metadata")
    except Exception as e:
        _record_error("fetch_property_prices/meta", e)
        cached = _load_cache("property_prices")
        if cached is not None:
            return {k: float(v) for k, v in cached.items()}
        return {}

    query_items = []

    for var in variables:
        code = var["code"]
        values = var["values"]
        code_lower = code.lower()

        value_texts = var.get("valueTexts", [])
        if code_lower in ("vuosineljännes", "quarter", "vuosi", "year"):
            # Take latest available
            query_items.append({"code": code, "selection": {"filter": "item", "values": [values[-1]]}})
        elif code_lower in ("postinumero", "postal code", "alue", "postinumeroalue"):
            query_items.append({"code": code, "selection": {"filter": "all", "values": ["*"]}})
        elif code_lower in ("tiedot", "information"):
            # Only the price-per-m² measure, never the transaction count.
            price_vals = [v for v in values if "hinta" in v.lower() or "price" in v.lower()]
            query_items.append({"code": code, "selection": {"filter": "item", "values": price_vals or [values[0]]}})
        elif code_lower in ("talotyyppi", "building type"):
            # A single representative dwelling type — two-room block of flats,
            # the standard reference unit for Finnish apartment prices.
            pick = next(
                (v for v, txt in zip(values, value_texts) if "two-room" in txt.lower() or "two room" in txt.lower()),
                None,
            )
            query_items.append({"code": code, "selection": {"filter": "item", "values": [pick or values[0]]}})
        else:
            query_items.append({"code": code, "selection": {"filter": "all", "values": ["*"]}})

    query = {"query": query_items, "response": {"format": "json"}}

    _rate_limit()

    try:
        r = _request_with_retry(
            "POST", PROPERTY_PRICE_URL, label="property price data",
            json=query, timeout=60,
        )
        data = r.json()
        columns, rows = _validate_pxweb_data(data, "property price data")
    except Exception as e:
        _record_error("fetch_property_prices/data", e)
        cached = _load_cache("property_prices")
        if cached is not None:
            return {k: float(v) for k, v in cached.items()}
        return {}

    result = {}
    try:
        pno_idx = None
        for i, col in enumerate(columns):
            code_lower = col.get("code", "").lower()
            if code_lower in ("postinumero", "postal code", "alue", "postinumeroalue"):
                pno_idx = i

        if pno_idx is not None:
            for row in rows:
                keys = row.get("key", [])
                vals = row.get("values", [])
                if not keys or not vals:
                    continue
                pno = keys[pno_idx][:5]
                val = vals[0]
                if val not in (None, "..", "...", ""):
                    try:
                        price = float(val)
                        # Keep the highest/latest value per postal code
                        if pno not in result or price > result[pno]:
                            result[pno] = price
                    except (ValueError, TypeError):
                        # Skip rows whose value isn't a parseable number.
                        pass

        logger.info("  Parsed property prices for %s postal codes", len(result))
        if result:
            _save_cache("property_prices", result)
    except Exception as e:
        _record_error("fetch_property_prices/parse", e)

    return result


def join_property_prices(gdf, price_data):
    """Join property price (€/m²) data to the GeoDataFrame.

    Merges API result with local fallback file for best coverage.
    """
    # Merge with local file if it exists
    if PROPERTY_PRICE_FILE.exists():
        try:
            with open(PROPERTY_PRICE_FILE, encoding="utf-8") as f:
                local = json.load(f)
            if local and isinstance(local, dict):
                # CF-16: the committed property_prices.json is produced by the
                # sales-count-weighted multi-year ashi 13mu method (fetch_property_prices.py)
                # and is authoritative; the narrow in-pipeline fetch only fills gaps.
                merged = {k: float(v) for k, v in (price_data or {}).items()}
                merged.update({k: float(v) for k, v in local.items()})
                price_data = merged
                logger.info("  Merged with local file: %d total entries", len(price_data))
        except Exception:
            # Optional local fallback file; ignore if missing/unreadable/invalid.
            pass

    if not price_data:
        gdf["property_price_sqm"] = None
        return gdf

    logger.info("Joining property price data...")
    for idx, row in gdf.iterrows():
        pno = row.get("pno", "")
        gdf.at[idx, "property_price_sqm"] = price_data.get(pno)
    return gdf


