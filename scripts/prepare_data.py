# Retry helper
# ---------------------------------------------------------------------------

def _request_with_retry(method, url, *, label, retries=MAX_RETRIES, **kwargs):
    """Execute an HTTP request with exponential-backoff retries.

    Returns the Response object or raises on exhaustion.
    """
    kwargs.setdefault("timeout", 60)
    # Always send a User-Agent. The Overpass API rejects header-less requests
    # with HTTP 406, and other public APIs increasingly do the same. Merge with
    # any caller-supplied headers rather than clobbering them.
    headers = {"User-Agent": "naapurustot.fi data pipeline (+https://naapurustot.fi)"}
    headers.update(kwargs.get("headers") or {})
    kwargs["headers"] = headers
    last_exc = None
    for attempt in range(1, retries + 1):
        try:
            r = requests.request(method, url, **kwargs)
            r.raise_for_status()
            return r
        except requests.RequestException as exc:
            last_exc = exc
            if attempt < retries:
                wait = RETRY_BACKOFF_BASE ** attempt
                logger.warning("Retry %d/%d for %s in %ds (%s)", attempt, retries, label, wait, exc)
                time.sleep(wait)
    if last_exc is None:
        # Unreachable in practice (retries >= 1 always sets last_exc), but guard
        # against raising None, which would mask the real failure with a TypeError.
        raise RuntimeError(f"{label}: request failed without capturing an exception")
    raise last_exc


def _fetch_cached(method, url, *, cache_key, label, **kwargs):
    """Fetch from URL with retry; on success cache the JSON, on failure load from cache.

    Returns the parsed JSON data, or None if both fetch and cache miss.
    """
    try:
        r = _request_with_retry(method, url, label=label, **kwargs)
        data = r.json()
        _save_cache(cache_key, data)
        return data
    except Exception as e:
        _record_error(label, e)
        logger.warning("  Fetch failed for %s, trying cache...", label)
        cached = _load_cache(cache_key)
        if cached is not None:
            return cached
        logger.warning("  No cache available for %s", label)
        return None


def _detect_latest_paavo_year() -> int:
    """Query WFS GetCapabilities to find the latest pno_tilasto_YYYY layer.

    Returns the year as an integer, or WFS_FALLBACK_YEAR if detection fails.
    Tries years in descending order since the newest advertised layer may not
    be queryable yet.
    """
    import re

    try:
        r = _request_with_retry(
            "GET", WFS_CAPABILITIES_URL, label="WFS GetCapabilities", timeout=30,
        )
        text = r.text
        years = sorted(set(int(m) for m in re.findall(r"pno_tilasto_(\d{4})", text)), reverse=True)
        if years:
            logger.info("Detected Paavo years: %s", years)
            for year in years:
                test_url = WFS_FEATURE_TEMPLATE.format(year=year) + "&count=1"
                try:
                    _request_with_retry("GET", test_url, label=f"Paavo probe {year}", timeout=30)
                    logger.info("Using Paavo year: %d", year)
                    return year
                except Exception:
                    logger.warning("  Paavo year %d not queryable, trying older...", year)
            logger.warning("  No Paavo year was queryable, using fallback: %d", WFS_FALLBACK_YEAR)
            return WFS_FALLBACK_YEAR
    except Exception as e:
        _record_error("detect_paavo_year", e)

    logger.warning("  Could not detect latest Paavo year, using fallback: %d", WFS_FALLBACK_YEAR)
    return WFS_FALLBACK_YEAR


